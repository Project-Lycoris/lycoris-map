export function useAdminUi() {
    const ui = useUi()
    return {
        ...ui,
        message: (value: string) =>
            ui.language === 'zh' && Object.hasOwn(messages, value)
                ? messages[value as keyof typeof messages]
                : ui.message(value),
    }
}
