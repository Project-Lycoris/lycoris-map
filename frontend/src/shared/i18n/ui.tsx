export type UiKey = keyof typeof uiMessages
export function localize(
    language: Language,
    text: string,
    values?: Record<string, string | number>,
): string {
    const prefix = 'The place step is saved. Photo upload paused: '
    if (text.startsWith(prefix))
        return localize(language, 'The place step is saved. Photo upload paused: {error}', {
            error: localize(language, text.slice(prefix.length)),
        })
    const template =
        language === 'zh' && Object.hasOwn(uiMessages, text) ? uiMessages[text as UiKey] : text
    return template.replace(/\{(\w+)\}/g, (token, name: string) =>
        values?.[name] === undefined ? token : String(values[name]),
    )
}
const Context = createContext<Language | null>(null)
export function UiLanguage({ language, children }: { language: Language; children: ReactNode }) {
    return <Context value={language}>{children}</Context>
}
export function useUi() {
    const override = useContext(Context),
        base = useOptionalLanguage()
    const language = override ?? base?.language ?? 'en'
    return {
        language,
        text: (key: UiKey, values?: Record<string, string | number>) =>
            localize(language, key, values),
        message: (value: string | null | undefined) => (value ? localize(language, value) : ''),
    }
}
