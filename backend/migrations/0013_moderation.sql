-- 管理后台 v2：审核理由与审核事件。
--
-- review_note 保存最近一次拒绝理由（可为空）；条目之后被通过或恢复时清空。
-- moderation_events 记录管理员审核/管理操作，与业务写入在同一事务内提交。
ALTER TABLE map_markers            ADD COLUMN review_note VARCHAR(500);
ALTER TABLE marker_edit_proposals  ADD COLUMN review_note VARCHAR(500);
ALTER TABLE marker_image_proposals ADD COLUMN review_note VARCHAR(500);

CREATE TABLE moderation_events (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    actor_public_id  VARCHAR(64) NOT NULL,
    actor_username   VARCHAR(255) NOT NULL,
    action           VARCHAR(32) NOT NULL,
    target_kind      VARCHAR(16) NOT NULL,
    target_id        BIGINT NOT NULL,
    marker_id        BIGINT,
    note             VARCHAR(500)
);
CREATE INDEX moderation_events_marker_idx  ON moderation_events (marker_id, created_at DESC);
CREATE INDEX moderation_events_created_idx ON moderation_events (created_at DESC);
